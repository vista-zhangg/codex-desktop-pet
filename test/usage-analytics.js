'use strict';
const assert = require('assert');
const { spawnSync } = require('child_process');
const { buildPanelUsage, panelRow } = require('../backend/panel-stats');
const { normalizeSourceRow } = require('../backend/usage-stats');
const A = require('../shared/usage-analytics');
const { modelHistory } = require('../backend/metering-common');
const now = new Date(2026, 9, 3, 14).getTime();
const row = (input, cache, cost = 1) => ({ input, cachedInput: cache, output: 10, tokens: input + 10, msgs: 1, cost });
const meters = [
  ['codex', { today: row(100, 80), lifetime: row(5000, 1000, 25), byModel: { gpt: row(100, 80) }, daily: { '2026-10-03': row(90, 70), '2026-10-02': row(900, 90), '2026-10-01': row(100, 50), '2026-09-30': { input: 0, output: 0, tokens: 0, cost: 0 }, 'invalid': row(10, 1) }, byModelByDay: { '2026-10-02': { gpt: row(900, 90) }, '2026-10-01': { gpt: row(100, 50) } } }],
  ['claude', { today: { input: 100, cacheRead: 40, cacheWrite5m: 20, cacheWrite1h: 10, output: 30, tokens: 200, cost: 2 }, lifetime: { tokens: 10000, cost: 0 }, byModel: { sonnet: { tokens: 200, cost: 2 } }, daily: {} }],
];
const snapshot = JSON.stringify(meters);
const data = buildPanelUsage(meters, now);
assert.equal(JSON.stringify(meters), snapshot, 'projection never mutates ledgers');
const history = modelHistory(meters[0][1].byModelByDay);
history['2026-10-02'].gpt.tokens = 0;
assert.equal(meters[0][1].byModelByDay['2026-10-02'].gpt.tokens, 910, 'model snapshots are detached from persisted state');
assert.equal(data.sources[1].daily['2026-10-03'].tokens, 110, 'live today replaces stale daily, never adds');
assert(!data.sources[1].daily.invalid, 'invalid dates excluded');
const today = A.selection(data, { range: 'today', source: 'all' });
assert.equal(today.current.tokens, 310);
assert.equal(today.current.inputTotal, 270, 'cache subsets included once across sources');
assert.equal(today.current.cacheRead, 120);
assert.equal(today.current.cacheWrite, 30);
assert.equal(today.current.normalInput, 120);
assert.equal(today.current.cacheRate, 120 / 270 * 100, 'ratio of sums, never mean of ratios');
assert(!today.comparable, 'partial today never compared against full yesterday');
const seven = A.selection(data, { range: '7d', source: 'codex' });
assert.equal(seven.start, '2026-09-26'); assert.equal(seven.end, '2026-10-02');
assert.equal(seven.current.tokens, 1020, 'complete days exclude today');
assert(Math.abs(seven.current.cacheRate - 14) < 1e-10, 'weighted aggregate cache rate');
assert(!seven.comparable, 'missing days prevent misleading percentage');
assert.equal(seven.byModel.reduce((n, r) => n + r.tokens, 0), seven.current.tokens);
const day = A.selection(data, { range: 'day', day: '2026-10-02', source: 'codex' });
assert(day.comparable); assert.equal(day.previous.tokens, 110);
assert.equal(day.byModel[0].name, 'gpt', 'historical model breakdown uses historical rows');
const missing = A.selection(data, { range: 'day', day: '2026-09-29', source: 'codex' });
const zero = A.selection(data, { range: 'day', day: '2026-09-30', source: 'codex' });
assert.equal(missing.current.known, false); assert.equal(zero.current.known, true);
assert.equal(zero.current.cacheRate, null, 'zero input is not 0% hit rate');
assert.equal(A.activity(data, 'codex').length, 90);
assert.equal(A.activity(data, 'codex')[0].key, '2026-07-06');
const weekly = A.chartPoints(A.activity(data, 'codex'), 'weekly');
assert(weekly.at(-1).partial, 'current week marked partial');
assert.equal(weekly.reduce((n, r) => n + r.value, 0), 1130);
const cumulative = A.chartPoints(A.activity(data, 'codex'), 'cumulative');
assert.equal(cumulative.at(-1).value, 1130, 'window cumulative excludes lifetime');
assert.equal(A.sum(A.sources(data, 'codex').map(s => s.lifetime)).tokens, 5010);
const legacy = panelRow('claude', { tokens: 100, cost: 1 });
assert.equal(legacy.detailComplete, false, 'legacy aggregate-only rows do not imply a zero input/cache rate');
assert.equal(A.sum([legacy]).cacheRate, null);
for (const source of ['codex', 'workbuddy', 'trae']) {
  const normalized = panelRow(source, { input: 100, cachedInput: 60, output: 10, tokens: 110 });
  assert.equal(normalized.inputTotal, 100, source + ' input already includes cache');
}
assert.equal(panelRow('zcode', { input: 50, cachedInput: 20, cacheWrite: 5, output: 10, tokens: 85 }).inputTotal, 75);
const empty = buildPanelUsage([['codex', { today: { tokens: 0 }, daily: {} }]], now);
assert(!A.selection(empty, { range: 'today' }).current.known, 'synthesized empty today is not a recorded zero day');
assert.equal(normalizeSourceRow('codex', { input: 50, inputTotal: null }).inputTotal, 50, 'null is not an explicit input total');
const oldCache = panelRow('claude', { input: 100, cacheCreate: 20, cacheRead: 30, output: 10, tokens: 160 });
assert.equal(oldCache.cacheWrite, 20, 'legacy cacheCreate retained');
assert.equal(oldCache.cacheWriteUnspecified, 20, 'legacy write does not invent a TTL');
const separate = panelRow('opencode', { input: 100, cachedInput: 50, cacheWrite: 20, output: 10, tokens: 180, reasoningOutput: 5 });
assert.equal(separate.inputTotal, 170); assert.equal(separate.tokens, 180, 'reasoning subset not re-added');
assert.equal(separate.cacheWrite5m, 0, 'generic writes are not 5-minute Claude writes');
assert.equal(separate.cacheWriteUnspecified, 20);
const bad = buildPanelUsage([['codex', { daily: { '2026-10-02': row(100, 10) }, byModelByDay: { '2026-10-02': { bogus: row(500, 10) } } }]], now);
const fallback = A.selection(bad, { range: 'day', day: '2026-10-02' });
assert.equal(fallback.byModel[0].name, '模型明细缺失');
assert.equal(fallback.byModel[0].tokens, 110, 'inconsistent models never exceed total');
const unavailable = JSON.parse(JSON.stringify(data)); unavailable.sources[1].unavailable = true;
assert(!A.selection(unavailable, { range: 'day', day: '2026-10-02', source: 'codex' }).comparable);
const dst = spawnSync(process.execPath, ['-e', `const a=require('./shared/usage-analytics');const assert=require('assert');assert.equal(a.offset('2026-03-08',1),'2026-03-09');assert.equal(a.offset('2026-11-01',-1),'2026-10-31');`], { cwd: require('path').join(__dirname, '..'), env: { ...process.env, TZ: 'America/New_York' } });
assert.equal(dst.status, 0, dst.stderr.toString());
console.log('usage analytics: normalization, range/source scope, missing/zero, model reconciliation, lifetime and DST passed');
